"""Collect all pilot result JSONs into results/SUMMARY.md (markdown tables)."""
import glob
import json
import os

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, "results")


def load(pattern):
    return [json.load(open(f)) for f in sorted(glob.glob(os.path.join(RES, pattern)))]


def spearman(a, b):
    a, b = np.asarray(a, float), np.asarray(b, float)
    ra, rb = a.argsort().argsort(), b.argsort().argsort()
    return float(np.corrcoef(ra, rb)[0, 1])


def main():
    out = ["# Pilot results summary", "", "Auto-generated by `summarize.py` from `results/*.json`.", ""]

    # ---- pilot 1
    p1 = load("pilot1_*_L*_H*.json")
    if p1:
        srcs = ["static", "staticwin", "phase", "back", "back_recent", "fut"]
        out += ["## Pilot 1 — dynamic / phase-conditioned dependency graphs", "",
                "Ridge graph-linear model, test MSE gain vs channel-independent (%). `fut` = oracle (uses the realised "
                "future-window correlation; optimistic upper bound). MAD = mean |error| of the relation estimate vs the "
                "realised future-window correlation (lower = better).", "",
                "| dataset | C | L/H | " + " | ".join(srcs) + " | MAD back | MAD static | MAD phase |",
                "|---|---|---|" + "---|" * (len(srcs) + 3)]
        for r in p1:
            g, st = r["ridge_test"], r["relation_stats"]
            out.append(f"| {r['dataset']} | {r['C']} | {r['L']}/{r['H']} | " +
                       " | ".join(f"{g[s]['gain_vs_ci_%']:+.1f}" for s in srcs) +
                       f" | {st['back']['mad_to_Rfut_mean']:.3f} | {st['static']['mad_to_Rfut_mean']:.3f} | "
                       f"{st['phase']['mad_to_Rfut_mean']:.3f} |")
        out.append("")
    p1b = load("pilot1b_*.json")
    if p1b:
        names = ["ci", "shared", "own_phase", "nb_phase", "both_phase"]
        out += ["### Pilot 1b — phase-specific weights (static graph)", "",
                "Test MSE; gain vs `shared` [x, Ax] in brackets. `own_phase` = only own-history weights depend on the "
                "phase group (control), `nb_phase` = only neighbour weights do, `both_phase` = both. "
                "Extra gain of `both_phase` over `own_phase` isolates phase-dependent use of neighbours.", "",
                "| dataset | " + " | ".join(names) + " | both vs own |", "|---|" + "---|" * (len(names) + 1)]
        for r in p1b:
            m = r["test_mse"]
            extra = 100 * (m["own_phase"] - m["both_phase"]) / m["own_phase"]
            out.append(f"| {r['dataset']} | " + " | ".join(f"{m[n]:.4f} ({r['gain_vs_shared_%'][n]:+.1f}%)" for n in names)
                       + f" | {extra:+.1f}% |")
        out.append("")

    # ---- pilot 2
    syn = load("pilot2_synthetic.json")
    if syn:
        s = syn[0]
        out += ["## Pilot 2A — synthetic factor + sparse-graph data (ground truth known)", "",
                "Structure recovery AUROC against the true (undirected) parent graph, and forecasting gain vs CI (%), "
                "mean over 3 seeds per setting.", ""]
        for switch in [False, True]:
            runs = [r for r in s["runs"] if r["switch"] == switch]
            est = list(runs[0]["structure"].keys())
            out.append(f"**{'regime-switching graph' if switch else 'static graph'}** — AUROC: " + ", ".join(
                f"{e} {np.mean([r['structure'][e]['auroc'] for r in runs]):.2f}" for e in est))
            out.append("")
            fc = list(runs[0]["forecast_gain_vs_CI_%"].keys())
            out.append("| model | " + " | ".join(fc) + " |")
            out.append("|---|" + "---|" * len(fc))
            out.append("| gain vs CI % | " + " | ".join(
                f"{np.mean([r['forecast_gain_vs_CI_%'][k] for r in runs]):+.1f}" for k in fc) + " |")
            out.append("")
    p2 = load("pilot2_real_*.json")
    if p2:
        variants = ["ci", "attn", "dense", "factor", "sparse", "factor_sparse"]
        out += ["## Pilot 2B/2C — real data: diagnostics and channel-mixing variants", "",
                "Same backbone (2 layers, D=64), same budget; only the channel-mixing block differs. L=96, H=96. "
                "Cells: test MSE (gain vs CI %).", "",
                "| dataset | C | PC1 share | probe: +graph | probe: +factor | " + " | ".join(variants) + " |",
                "|---|---|---|---|---|" + "---|" * len(variants)]
        rows = []
        for r in p2:
            m, d = r["models"], r["diagnostics"]
            if "ci" not in m:
                continue
            base = m["ci"]["test_mse"]
            cells = []
            for v in variants:
                if v in m:
                    cells.append(f"{m[v]['test_mse']:.4f} ({100*(base-m[v]['test_mse'])/base:+.1f}%)")
                else:
                    cells.append("—")
            lp = d["linear_probe"]
            out.append(f"| {r['dataset']} | {d['C']} | {d['pc1_share']:.2f} | {lp['graph']['gain_vs_ci_%']:+.1f}% | "
                       f"{lp['factor']['gain_vs_ci_%']:+.1f}% | " + " | ".join(cells) + " |")
            cd = [100 * (base - m[v]["test_mse"]) / base for v in variants[1:] if v in m]
            rows.append((r["dataset"], d, max(cd) if cd else np.nan, m))
        out.append("")
        if len(rows) >= 5:
            best_cd = [x[2] for x in rows]
            diags = {"PC1 share": [x[1]["pc1_share"] for x in rows],
                     "raw coupling": [x[1]["raw_coupling_topk"] for x in rows],
                     "residual coupling": [x[1]["resid_coupling_topk"] for x in rows],
                     "linear probe +graph gain": [x[1]["linear_probe"]["graph"]["gain_vs_ci_%"] for x in rows],
                     "linear probe +factor gain": [x[1]["linear_probe"]["factor"]["gain_vs_ci_%"] for x in rows],
                     "C (number of variables)": [x[1]["C"] for x in rows]}
            out += [f"Spearman correlation across {len(rows)} datasets between a diagnostic (train/val only) and the best "
                    "neural CD gain on test:", ""]
            for k, v in diags.items():
                out.append(f"- {k}: ρ = {spearman(v, best_cd):+.2f}")
            wins = {v: 0 for v in variants[1:]}
            for _, _, _, m in rows:
                cdv = {v: m[v]["test_mse"] for v in variants[1:] if v in m}
                if cdv:
                    wins[min(cdv, key=cdv.get)] += 1
            out += ["", "Best CD variant count: " + ", ".join(f"{k} {v}" for k, v in wins.items()), ""]

    # ---- pilot 3
    p3 = load("pilot3_order_*.json")
    if p3:
        out += ["## Pilot 3 — Mamba channel-scan order", "",
                "Same model and seed, only the order differs (`seedN` rows = original order with another seed, i.e. the "
                "noise floor). LA = normalised linear-arrangement cost of the order on the top-k |corr| graph.", ""]
        for r in p3:
            out.append(f"**{r['dataset']}** (C={r['C']}, H={r['H']})")
            out.append("")
            out.append("| run | order | LA cost | test MSE |")
            out.append("|---|---|---|---|")
            for k, v in sorted(r["runs"].items(), key=lambda kv: kv[1]["test_mse"]):
                la = v.get("la_cost")
                out.append(f"| {k} | {v.get('order')} | {la if la is None else round(la, 3)} | {v['test_mse']:.4f} |")
            bi = {k: v for k, v in r["runs"].items() if k.startswith("bi16_") and "seed" not in k}
            if len(bi) >= 3:
                rho = spearman([v["la_cost"] for v in bi.values()], [v["test_mse"] for v in bi.values()])
                mses = [v["test_mse"] for v in bi.values()]
                seeds = [v["test_mse"] for k, v in r["runs"].items() if "seed" in k] + \
                        ([r["runs"]["bi16_original"]["test_mse"]] if "bi16_original" in r["runs"] else [])
                out.append("")
                out.append(f"bi16 orders: MSE range {min(mses):.4f}–{max(mses):.4f} "
                           f"(spread {100*(max(mses)-min(mses))/min(mses):.1f}%), Spearman(LA, MSE) = {rho:+.2f}; "
                           f"seed spread (original order) {100*(max(seeds)-min(seeds))/min(seeds):.1f}%")
            out.append("")

    # ---- pilot 4
    p4 = load("pilot4_*.json")
    if p4:
        out += ["## Pilot 4 — adaptive test-time compute in coarse-to-fine forecasting", "",
                "Fixed-k frontier = piecewise-linear interpolation between fixed stopping points (achievable by randomly "
                "mixing stopping steps). 'Halting vs frontier' = largest MSE reduction of the learned halting policy "
                "relative to the frontier at equal FLOPs; 'FLOPs to reach best fixed MSE +1%' compares compute needed.", "",
                "| dataset | MSE k=1 | k=2 | k=3 | k=4 | top-20% share of refinement gain | samples hurt by refinement | "
                "oracle per-sample stop | halting vs frontier (max, at FLOPs) | FLOPs to reach best fixed +1%: halting / fixed |",
                "|---|---|---|---|---|---|---|---|---|---|"]
        for r in p4:
            f = r["fixed_k"]
            fx = np.array([f[k]["rel_flops"] for k in ["k=1", "k=2", "k=3", "k=4"]])
            fm = np.array([f[k]["mse"] for k in ["k=1", "k=2", "k=3", "k=4"]])
            fm_front = np.minimum.accumulate(fm)  # more compute never needs to be worse (stop earlier)
            best_gain, at = 0.0, None
            for c in r["learned_halting_curve"]:
                if fx[0] <= c["rel_flops"] <= fx[-1]:
                    ref = np.interp(c["rel_flops"], fx, fm_front)
                    g = 100 * (ref - c["mse"]) / ref
                    if g > best_gain:
                        best_gain, at = g, c["rel_flops"]
            target = fm.min() * 1.01
            fl_fixed = float(fx[np.argmax(fm_front <= target)])
            ok = [c["rel_flops"] for c in r["learned_halting_curve"] if c["mse"] <= target]
            fl_halt = min(ok) if ok else float("nan")
            out.append(f"| {r['dataset']} | " + " | ".join(f"{m:.4f}" for m in fm) +
                       f" | {100*r['refinement_gain']['share_of_total_gain_from_top20pct']:.0f}% | "
                       f"{100*r['refinement_gain']['frac_samples_hurt_by_refinement']:.0f}% | "
                       f"{r['oracle_per_sample']['mse']:.4f} | {best_gain:+.1f}% @ {at if at is None else round(at, 2)} | "
                       f"{fl_halt:.2f} / {fl_fixed:.2f} |")
        out.append("")

    # ---- pilot 5
    p5 = load("pilot5_*.json")
    if p5:
        out += ["## Pilot 5 — cross-variable information on top of a foundation model (Chronos-2)", "",
                "Gain vs Chronos-2 univariate zero-shot (%), test windows only.", ""]
        keys = list(p5[0]["gain_vs_uni_zero_shot_%"].keys())
        out += ["| dataset | C | uni MSE | " + " | ".join(keys) + " |", "|---|---|---|" + "---|" * len(keys)]
        for r in p5:
            out.append(f"| {r['dataset']} | {r['C']} | {r['zero_shot']['uni']['mse']:.4f} | " +
                       " | ".join(f"{r['gain_vs_uni_zero_shot_%'][k]:+.1f}" for k in keys) + " |")
        out.append("")

    # ---- pilot 6
    p6 = load("pilot6_*.json")
    if p6:
        out += ["## Pilot 6 — LLM-written semantic prior graph", "",
                "Edge weights always come from train correlations; only the edge set differs. Gain vs CI (%).", "",
                "| dataset | regime | prior-vs-data AUROC | prior | data (degree-matched) | prior ∪ data | random (mean of 5) |",
                "|---|---|---|---|---|---|---|"]
        for r in p6:
            for reg, o in r["regimes"].items():
                g = o["gain_vs_ci_%"]
                out.append(f"| {r['dataset']} | {reg} | {o['prior_vs_data_auroc(top-quartile |corr| pairs)']:.2f} | "
                           f"{g['prior_graph']:+.2f} | {g['data_graph']:+.2f} | {g['prior_or_data']:+.2f} | "
                           f"{g['random_graph_mean']:+.2f} |")
        out.append("")

    path = os.path.join(RES, "SUMMARY.md")
    open(path, "w").write("\n".join(out))
    print("\n".join(out))


if __name__ == "__main__":
    main()
